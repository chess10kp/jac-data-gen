#!/usr/bin/env bash
# Regenerate the Jac grounding the composer injects so the LLM grounds on real
# Jac idiom instead of hallucinating (Jac is new, thin in pretraining).
#
#   jac_grounding.md   BASE syntax reference (cheatsheet + types) — every hole needs it.
#   jac_skills/<t>.md  ROUTABLE topic guides — attached per-entry by the skill router
#                      (pipeline/composer.py::skills_for_record) only when a
#                      record's holes actually involve that construct.
#
# Bump the topic list here if the composer keeps failing on a construct no guide
# covers, and add a matching signal in the router.
set -euo pipefail
JAC_REPO=/home/jac/repos/jac_llm_data/jaseci/jac
DIR="$(cd "$(dirname "$0")/.." && pwd)"
SKILLS="$DIR/jac_skills"
cd "$JAC_REPO"
mkdir -p "$SKILLS"

# BASE — always injected for generation batches.
{
  echo "<!-- Auto-generated by gen_grounding.sh: jac guide jac-core-cheatsheet + jac-types -->"
  echo "# Jac language grounding (authoritative — prefer over prior knowledge)"
  echo; echo "## Core cheatsheet"
  jac guide jac-core-cheatsheet 2>/dev/null | grep -v "dev mode"
  echo; echo "## Type system"
  jac guide jac-types 2>/dev/null | grep -v "dev mode"
} > "$DIR/jac_grounding.md"

# ROUTABLE topics — one file each, attached only when relevant to an entry.
TOPICS=(jac-has-fields jac-cl-components jac-cl-styling jac-cl-js-interop
        jac-cl-routing jac-cl-organization jac-by-llm jac-npm-packages)
for t in "${TOPICS[@]}"; do
  jac guide "$t" 2>/dev/null | grep -v "dev mode" > "$SKILLS/$t.md"
done
echo "wrote jac_grounding.md ($(wc -l < "$DIR/jac_grounding.md") lines) + ${#TOPICS[@]} skills in jac_skills/"
